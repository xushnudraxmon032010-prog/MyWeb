do $$
begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'acquaintances' and column_name = 'firstname') then
    alter table public.acquaintances rename column firstname to "firstName";
  end if;
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'acquaintances' and column_name = 'lastname') then
    alter table public.acquaintances rename column lastname to "lastName";
  end if;
end $$;

alter table public.profile enable row level security;
alter table public.friends enable row level security;
alter table public.acquaintances enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "Public can read profile" on public.profile;
drop policy if exists "Public can read friends" on public.friends;
do $$
declare
  existing_policy record;
begin
  for existing_policy in
    select policyname from pg_policies where schemaname = 'public' and tablename = 'acquaintances'
  loop
    execute format('drop policy if exists %I on public.acquaintances', existing_policy.policyname);
  end loop;
end $$;

create policy "Public can read profile" on public.profile for select to anon, authenticated using (true);
create policy "Public can read friends" on public.friends for select to anon, authenticated using (true);
create policy "Public can submit requests" on public.acquaintances for insert to public with check (status = 'pending');
create policy "Public can read approved" on public.acquaintances for select to anon, authenticated using (status = 'approved');
create policy "Authenticated can manage friends" on public.friends for all to authenticated using (true) with check (true);
create policy "Authenticated can manage acquaintances" on public.acquaintances for all to authenticated using (true) with check (true);
drop policy if exists "Public can submit reviews" on public.reviews;
drop policy if exists "Authenticated can manage reviews" on public.reviews;
drop policy if exists "Anon can submit reviews" on public.reviews;
drop policy if exists "Authenticated can submit reviews" on public.reviews;
create policy "Anon can submit reviews" on public.reviews for insert to anon with check (true);
create policy "Authenticated can submit reviews" on public.reviews for insert to authenticated with check (true);
create policy "Authenticated can manage reviews" on public.reviews for all to authenticated using (true) with check (true);
grant usage on schema public to anon, authenticated;
grant insert on table public.reviews to anon, authenticated;