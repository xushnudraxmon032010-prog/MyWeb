create table if not exists public.profile (
  id bigint primary key check (id = 1), name text not null, surname text default '', title text default '', city text default '',
  bio text default '', about text default '', course text default '', interests jsonb not null default '[]'::jsonb,
  achievements jsonb not null default '[]'::jsonb, telegram text default '', instagram text default '', youtube text default ''
);

create table if not exists public.friends (
  id bigint generated by default as identity primary key, name text not null, relation text default 'Do’st', note text default ''
);

create table if not exists public.acquaintances (
  id bigint generated by default as identity primary key, "firstName" text not null, "lastName" text not null,
  age integer default 0, phone text not null, status text not null default 'pending' check (status in ('pending', 'approved'))
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null default 'Noma’lum',
  rating integer not null check (rating between 1 and 5),
  comment text not null check (char_length(trim(comment)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create table if not exists public.visitor_events (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  visited_at timestamptz not null default now()
);

