create or replace function public.get_monthly_visitor_stats()
returns table(month date, unique_visitors bigint, visits bigint)
language sql
security definer
set search_path = public
as $$
  select
    date_trunc('month', visited_at)::date as month,
    count(distinct visitor_id) as unique_visitors,
    count(*) as visits
  from public.visitor_events
  where visited_at >= date_trunc('month', current_date) - interval '11 months'
  group by 1
  order by 1;
$$;

revoke all on function public.get_monthly_visitor_stats() from public;
grant execute on function public.get_monthly_visitor_stats() to authenticated;